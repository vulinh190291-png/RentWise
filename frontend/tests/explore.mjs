import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage()
page.setDefaultTimeout(6000)
const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5174'
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
 await page.goto(base + '/explore')
 await page.getByRole('heading', { name: '从一座城，读懂一种生活。' }).waitFor()
 const search = page.getByRole('searchbox', { name: '搜索城市、拼音或住宅特点' })
 await page.locator('.city-choice').first().waitFor()
 assert.equal(await page.locator('.city-choice').count(), 8)
 await page.locator('.city-choice').first().click()
 await search.fill('无匹配的城市')
 await page.setViewportSize({width:390,height:844})
 assert.equal(await search.isVisible(),true,'empty search remains recoverable across desktop/mobile breakpoint')
 await page.getByRole('button',{name:'清空搜索'}).click()
 await page.setViewportSize({width:1280,height:800})
 await search.fill('院落')
 assert.equal(await page.locator('.city-choice').count(),2)
 await page.getByRole('button',{name:'清空搜索'}).click()
 const payload = JSON.parse(await readFile(new URL('../public/data/explore-cities.json',import.meta.url),'utf8'))
 for (const city of payload.cities) {
  await page.locator('.city-choice').filter({hasText:city.name}).click()
  await page.getByRole('heading',{name:city.name,exact:true}).waitFor()
  await page.locator('.sources summary').click()
  assert.equal(await page.locator('.sources a').count(),city.sources.length)
  await page.locator('.sources summary').click()
  await page.getByRole('button',{name:'返回城市列表'}).click()
 }
 await search.fill(' SHANGHAI ')
 assert.equal(await page.locator('.city-choice').count(), 1)
 await page.locator('.city-choice').click()
 await page.getByRole('heading', { name: '上海', exact: true }).waitFor()
 await page.getByRole('button', { name: '返回城市列表' }).click()
 await search.fill('不存在的城市')
 await page.getByText('暂未找到匹配城市').waitFor()
 assert.equal(await page.locator('.city-detail').count(), 0)
 await page.getByRole('button', { name: '清空搜索' }).click()
 assert.equal(await page.locator('.city-choice').count(), 8)
 await page.locator('.city-choice').first().focus(); await page.keyboard.press('Enter')
 assert.equal(await page.locator('#city-title').evaluate(el => el === document.activeElement), true)
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('.city-choice').first().evaluate(el => el === document.activeElement), true)
 await page.getByRole('button', { name: '地图接入说明' }).click()
 await page.getByText('地图尚未开放', { exact: true }).waitFor()
 await page.getByRole('button', { name: '返回城市浏览' }).click()
 for (const [width,height] of [[1440,900],[1024,768],[390,844],[320,740]]) {
  await page.setViewportSize({width,height}); await page.goto(base+'/explore')
  await page.locator('.city-choice').first().waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  if (process.env.UI_SCREENSHOT_DIR) {
   await mkdir(process.env.UI_SCREENSHOT_DIR,{recursive:true})
   await page.screenshot({path:`${process.env.UI_SCREENSHOT_DIR}/explore-${width}.png`,fullPage:true})
  }
  await page.locator('.city-choice').last().click()
  await page.getByRole('heading',{name:'哈尔滨',exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  if (process.env.UI_SCREENSHOT_DIR) await page.screenshot({path:`${process.env.UI_SCREENSHOT_DIR}/explore-detail-${width}.png`,fullPage:true})
  await page.getByRole('button',{name:'返回城市列表'}).click()
  assert.equal(await page.locator('.city-choice').last().evaluate(el=>el===document.activeElement),true)
 }
 let release
 await page.route('**/data/explore-cities.json',async route=>{await new Promise(resolve=>{release=resolve});await route.continue()})
 await page.goto(base+'/explore'); await page.getByText('正在加载城市资料…').waitFor()
 release(); await page.locator('.city-choice').first().waitFor(); await page.unroute('**/data/explore-cities.json')
 for (const response of [{status:503,body:'unavailable'},{status:200,contentType:'application/json',body:'{"cities":[{}]}'},{status:200,contentType:'application/json',body:JSON.stringify({...payload,cities:[payload.cities[0],payload.cities[0]]})}]) {
  await page.route('**/data/explore-cities.json',route=>route.fulfill(response))
  await page.reload(); await page.getByRole('alert').filter({hasText:'城市资料暂不可用'}).waitFor()
  await page.unroute('**/data/explore-cities.json')
  await page.getByRole('button',{name:'重新加载'}).click(); await page.locator('.city-choice').first().waitFor()
 }
 await page.route('**/data/explore-cities.json',route=>route.fulfill({status:200,contentType:'application/json',body:'{"version":"0.1","cities":[]}'}))
 await page.reload(); await page.getByText('城市资料正在整理',{exact:true}).waitFor()
 await page.unroute('**/data/explore-cities.json')
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.route('**/images/housing-courtyard.webp',route=>route.abort())
 await page.reload(); await page.locator('.city-choice').first().waitFor()
 assert.equal(await page.locator('.intro figure').count(),0)
 await page.unroute('**/images/housing-courtyard.webp')
 await page.goto(base+'/login'); await page.getByRole('link',{name:'城市探索',exact:true}).click(); await page.waitForURL('**/explore')
 await page.locator('.city-choice').first().click()
 await page.getByRole('link',{name:'开始风险学习'}).click(); await page.waitForURL('**/login')
 assert.deepEqual(errors,[])
 console.log('PASS Explore: public entry, 8 cities, search/empty, selection, keyboard/focus, map notice, 4 viewports, loading/error/malformed/retry, protected learning entry.')
} finally { await browser.close() }
