// Run with PLAYWRIGHT_MODULE pointing to an installed playwright package.
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5173'
try {
 await page.goto(base + '/login')
 await page.getByRole('heading', { name: '欢迎回来。' }).waitFor()
 for (const width of [1440, 1024, 768, 390]) {
  await page.setViewportSize({width, height: 1000})
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`)
  const bounds = await page.locator('.showcase').boundingBox()
  const form = await page.locator('.login-side').boundingBox()
  assert(width >= 1024 ? form.x > bounds.x : form.y >= bounds.y + bounds.height - 1, `layout ${width}`)
  if (process.env.UI_SCREENSHOT_DIR) await page.screenshot({ path: `${process.env.UI_SCREENSHOT_DIR}/login-${width}.png`, fullPage: true })
 }
 await page.locator('#username').fill('retained-user')
 await page.getByRole('button', {name: '下一项住宅介绍'}).click()
 assert.equal(await page.locator('#username').inputValue(), 'retained-user')
 await page.getByRole('heading', {name: '复式空间', exact:true}).waitFor()
 const opener = page.getByRole('button', {name:'了解这类空间'})
 await opener.click()
 await page.getByRole('dialog').waitFor()
 for (let i=0;i<8;i++) { await page.keyboard.press('Tab'); assert(await page.evaluate(() => !!document.activeElement?.closest('[role=dialog]')), 'dialog focus escaped') }
 await page.keyboard.press('Escape')
 await page.getByRole('dialog').waitFor({state:'hidden'})
 await page.waitForFunction(() => document.activeElement?.textContent?.includes('了解这类空间'))
 await page.emulateMedia({reducedMotion:'reduce'})
 const title=await page.locator('.showcase h2').textContent()
 await page.waitForTimeout(8100)
 assert.equal(await page.locator('.showcase h2').textContent(),title)
 await page.locator('#username').fill('')
 await page.getByRole('button',{name:'登录，继续学习'}).click()
 await page.getByText('请输入用户名',{exact:true}).waitFor()
 await page.getByText('请输入密码',{exact:true}).waitFor()
 let calls=0
 await page.route('**/api/auth/login', async route => { calls++; await new Promise(r=>setTimeout(r,400)); await route.fulfill({status:401,json:{success:false,data:null,message:'账号或密码不正确'}}) })
 await page.locator('#username').fill('learner')
 await page.locator('#password').fill('password123')
 await page.locator('#password').press('Enter')
 await page.locator('#password').press('Enter')
 await page.getByRole('alert').filter({hasText:'账号或密码不正确'}).waitFor()
 assert.equal(calls,1,'duplicate login')
 assert.equal(await page.evaluate(()=>sessionStorage.getItem('rentwise_access_token')),null)
 await page.goto(base+'/register')
 await page.getByLabel('用户名',{exact:true}).fill('learner')
 await page.getByLabel('密码',{exact:true}).fill('password123')
 await page.getByLabel('确认密码',{exact:true}).fill('different')
 await page.getByRole('button',{name:'创 建 账 户'}).click()
 await page.getByText('两次输入的密码不一致',{exact:true}).waitFor()
 await page.route('**/api/auth/register', route=>route.fulfill({json:{success:true,data:{id:1,username:'learner',role:'LEARNER'},message:'OK'}}))
 await page.getByLabel('确认密码',{exact:true}).fill('password123')
 await page.getByRole('button',{name:'创 建 账 户'}).click()
 await page.waitForURL('**/login')
 await page.unroute('**/api/auth/login')
 await page.route('**/api/auth/login',route=>route.fulfill({json:{success:true,data:{accessToken:'test-only-ui-token',tokenType:'Bearer',expiresIn:3600},message:'OK'}}))
 await page.route('**/api/users/me',route=>route.fulfill({json:{success:true,data:{id:1,username:'learner',role:'LEARNER'},message:'OK'}}))
 await page.route('**/api/profile/me',route=>route.fulfill({json:{success:true,data:{userId:1,topics:[]},message:'OK'}}))
 await page.route('**/api/training/next',route=>route.fulfill({status:409,json:{success:false,data:null,message:'请先完成诊断'}}))
 await page.locator('#username').fill('learner');await page.locator('#password').fill('password123')
 await page.getByRole('button',{name:'登录，继续学习'}).click();await page.waitForURL('**/dashboard')
 assert.equal(await page.evaluate(()=>sessionStorage.getItem('rentwise_access_token')),'test-only-ui-token')
 await page.reload();await page.getByRole('button',{name:'退出登录'}).waitFor()
 assert.equal(await page.evaluate(()=>sessionStorage.getItem('rentwise_access_token')),'test-only-ui-token')
 await page.getByRole('button',{name:'退出登录'}).click();await page.waitForURL('**/login')
 assert.equal(await page.evaluate(()=>sessionStorage.getItem('rentwise_access_token')),null)
 await page.locator('#username').fill('learner');await page.locator('#password').fill('password123')
 await page.getByRole('button',{name:'登录，继续学习'}).click();await page.waitForURL('**/dashboard')
 await page.goto(base+'/login');await page.waitForURL('**/dashboard')
 await page.evaluate(()=>sessionStorage.clear())
 await page.goto(base+'/diagnosis');await page.waitForURL('**/login')
 await page.route('**/images/housing-placeholder.svg',route=>route.abort())
 await page.reload();await page.getByText('图片暂不可用 · 仍可阅读科普').waitFor()
 assert.deepEqual(errors,[])
 console.log('PASS: 4 viewports, carousel, form persistence, dialog focus/Escape, reduced motion, validation, duplicate prevention, mocked auth/register, guards, image fallback; no runtime errors.')
} finally { await browser.close() }
